import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const path='/computer-literacy/written/computer-basics/computer-classification/';
const prod=await fetch('https://getpasslab.co.kr'+path, {headers:{'Cache-Control':'no-cache'}});
assert(prod.ok,'cannot fetch production baseline');
const current=await prod.text();
const preview=await readFile('dist'+path+'index.html','utf8');
const article=html=>html.match(/<article\b[^>]*>([\s\S]*?)<\/article>/)?.[1]??'';
const a=article(current),b=article(preview);
let i=0;while(i<Math.min(a.length,b.length)&&a[i]===b[i])i++;
console.log('ARTICLE DEBUG production',a.length,'build',b.length,'firstDiffAt',i,'productionPreview',JSON.stringify(a.slice(Math.max(0,i-150),i+400)),'branchPreview',JSON.stringify(b.slice(Math.max(0,i-150),i+400)));
if(a===b)console.log('ARTICLE DEBUG identical to production');
